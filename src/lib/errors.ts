const FK_MESSAGE = "This is still in use, so it can't be deleted. Deactivate it instead.";

// Codes whose `details` names the item involved.
const WITH_DETAIL = new Set([
  "item_unavailable",
  "variation_required",
  "invalid_variation",
  "invalid_add_on",
  "add_on_selection_invalid",
  "table_too_small",
  "reservation_conflict",
]);

export function friendlyError(
  error: { message?: string; details?: string | null } | null | undefined,
): string {
  const message = error?.message;
  if (!message) return "Something went wrong.";
  const key = Object.keys(MESSAGES).find((k) => message.includes(k));
  if (key) return WITH_DETAIL.has(key) && error?.details ? `${MESSAGES[key]} (${error.details})` : MESSAGES[key];
  if (message.includes("duplicate key")) return "That already exists.";
  if (message.includes("foreign key")) return FK_MESSAGE;
  if (message.includes("row-level security")) return MESSAGES.forbidden;
  return message;
}
